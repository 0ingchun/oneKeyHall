import { readFile, writeFile, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = new URL('../', import.meta.url);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
function number(source, pattern, label) {
  const match = source.match(pattern);
  if (!match) throw new Error(`Cannot read ${label} from firmware source.`);
  return Number(match[1]);
}

// Hash decoded flash bytes, so Git's LF/CRLF conversion cannot change identity.
export function decodeHex(text) {
  const image = Buffer.alloc(0x3800, 0xff), written = new Set();
  let base = 0, ended = false;
  for (const line of text.trim().split(/\r?\n/)) {
    if (ended || !/^:(?:[\da-f]{2})+$/i.test(line)) throw new Error('Invalid HEX record.');
    const record = Buffer.from(line.slice(1), 'hex');
    const count = record[0], address = record.readUInt16BE(1), type = record[3];
    if (record.length !== count + 5 || record.reduce((sum, n) => sum + n, 0) % 256) throw new Error('Invalid HEX length/checksum.');
    if (type === 0) {
      for (let i = 0; i < count; ++i) {
        const at = base + address + i;
        if (at >= image.length || written.has(at)) throw new Error('HEX exceeds application Flash or overlaps records.');
        image[at] = record[4 + i]; written.add(at);
      }
    } else if (type === 1 && count === 0) ended = true;
    else if ((type === 2 || type === 4) && count === 2) base = record.readUInt16BE(4) * (type === 2 ? 16 : 65536);
    else throw new Error(`Unsupported HEX record type ${type}.`);
  }
  if (!ended || !written.size) throw new Error('Incomplete HEX file.');
  return image;
}

export function releaseMetadata(header, sketch, hex) {
  const versionParts = ['MAJOR', 'MINOR', 'PATCH'].map(part => number(header, new RegExp(`#define\\s+ONEKEYHALL_FW_${part}\\s+(\\d+)`), part));
  const configVersion = number(sketch, /#define\s+VERSION\s+(0x[\da-f]+|\d+)/i, 'config format');
  const configLength = number(sketch, /CONFIG_INDEX_LAST\s*=\s*(\d+)/, 'config length');
  const capabilities = number(sketch, /print_text\("\[1002,(\d+)\]/, 'capabilities');
  const isp = number(sketch, /print_text\(ONEKEYHALL_FW_FRAME\s+"(\d+)\]/, 'ISP support');
  const versionReply = `[1003,${versionParts.join(',')},${isp}]`;
  const image = decodeHex(hex);
  if (!image.includes(Buffer.from(versionReply)) || !image.includes(Buffer.from(`[1002,${capabilities}]`))) {
    throw new Error('HEX does not match the source release/capabilities. Rebuild firmware first.');
  }
  return { version: versionParts.join('.'), configVersion, configLength, capabilities, isp: !!isp, versionReply, firmwareSha256: hash(image) };
}

export async function syncRelease(check = true) {
  const [header, sketch, hex] = await Promise.all([
    readFile(new URL('firmware/src/FirmwareVersion.h', root), 'utf8'),
    readFile(new URL('firmware/firmware.ino', root), 'utf8'),
    readFile(new URL('firmware/build/onekeyhall-ch552-24mhz.hex', root), 'utf8'),
  ]);
  const release = releaseMetadata(header, sketch, hex);
  const output = '// Generated by scripts/sync-release.mjs after firmware build. Do not edit.\n' +
    `export const release = Object.freeze(${JSON.stringify(release, null, 2)});\n` +
    'export const configLabel = `V${String(release.configVersion).padStart(2, "0")}`;\n';
  const moduleUrl = new URL('host/assets/release.mjs', root);
  const publishedUrl = new URL('host/firmware/latest.hex', root);
  const docUrl = new URL('docs/CURRENT_RELEASE.md', root);
  const doc = `# 当前固件发布信息\n\n<!-- Generated by scripts/sync-release.mjs. Do not edit. -->\n\n` +
    `- 应用版本：V${release.version}\n- 配置格式：V${String(release.configVersion).padStart(2, '0')}，${release.configLength} 字节\n` +
    `- 能力值：${release.capabilities}（0x${release.capabilities.toString(16).toUpperCase()}）\n` +
    `- 版本查询应答：\`${release.versionReply}\`\n` +
    `- 应用 Flash 镜像 SHA-256：\`${release.firmwareSha256}\`\n\n` +
    `哈希针对解码后的 0x0000–0x37FF 应用镜像（空洞填 0xFF），不受 HEX 文本换行符影响。\n\n` +
    `[下载固件](../firmware/build/onekeyhall-ch552-24mhz.hex) · [串口协议](HALL_PROTOCOL.md) · [验证报告](../firmware/build/verification.json)\n\n` +
    `由固件源码与构建出的 HEX 生成，不代表已完成实机验收或在线部署。\n`;
  if (check) {
    if ((await readFile(moduleUrl, 'utf8')).replace(/\r\n/g, '\n') !== output ||
        hash(decodeHex(await readFile(publishedUrl, 'utf8'))) !== release.firmwareSha256 ||
        (await readFile(docUrl, 'utf8')).replace(/\r\n/g, '\n') !== doc) {
      throw new Error('Published release metadata/HEX is stale. Run the firmware build script before publishing.');
    }
  } else {
    await copyFile(new URL('firmware/build/onekeyhall-ch552-24mhz.hex', root), publishedUrl);
    await writeFile(moduleUrl, output);
    await writeFile(docUrl, doc);
  }
  return release;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (!['--check', '--write'].includes(process.argv[2])) throw new Error('Usage: node scripts/sync-release.mjs --check|--write');
    const release = await syncRelease(process.argv[2] === '--check');
    console.log(`Release ${release.version}: metadata and published firmware ${process.argv[2] === '--check' ? 'verified' : 'updated'}.`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
